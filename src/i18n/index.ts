export type MessageKey = keyof typeof messages.en;
export const localeLabels: Record<Locale, string> = { "zh-CN": "简体中文", "zh-TW": "繁體中文", en: "English", ja: "日本語", ko: "한국어" };
export const locales = Object.keys(localeLabels) as Locale[];
export function resolveLocale(language: Language, browserLanguage = typeof navigator === "undefined" ? "en" : navigator.language): Locale {
  if (language !== "system") return language;
  const value = browserLanguage.toLowerCase();
  if (value.startsWith("zh")) return /tw|hk|hant/.test(value) ? "zh-TW" : "zh-CN";
  if (value.startsWith("ja")) return "ja";
  if (value.startsWith("ko")) return "ko";
  return "en";
}
export function translate(locale: Locale, key: MessageKey, params: Record<string, string | number> = {}): string {
  let template = String(messages[locale][key]);
  if (locale === "en") {
    if (key === "totalSessions" && Number(params.value) === 1) template = template.replace("sessions", "session");
    if (key === "remaining") {
      if (Number(params.minutes) === 1) template = template.replace(" minutes", " minute");
      if (Number(params.seconds) === 1) template = template.replace(" seconds", " second");
    }
  }
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? "{" + name + "}"));
}
export type Translator = (key: MessageKey, params?: Record<string, string | number>) => string;
export function modeKey(mode: TimerMode): "focus" | "shortBreak" | "longBreak" { return mode; }
export function formatClock(ms: number): string { const seconds = Math.max(0, Math.ceil(ms / 1000)); return String(Math.floor(seconds / 60)).padStart(2, "0") + ":" + String(seconds % 60).padStart(2, "0"); }
export function localDateKey(date: Date): string { return date.getFullYear() + "-" + String(date.getMonth() + 1).padStart(2, "0") + "-" + String(date.getDate()).padStart(2, "0"); }
export function formatDuration(ms: number, t: Translator): string { return ms > 0 && ms < 60_000 ? t("lessThanMinute") : t("minutes", { value: Math.floor(Math.max(0, ms) / 60_000) }); }
